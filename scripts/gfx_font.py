GL = {}
for k, v in LAT.items(): GL[k] = v if isinstance(v, tuple) else ((2 if k.islower() else 0), v)
for k, v in LOW.items(): GL[k] = v if isinstance(v, tuple) else (2, v)
for k, v in UP.items(): GL[k] = v if isinstance(v, tuple) else (0, v)
for k, v in DIG.items(): GL[k] = (0, v)
GL.update(PUN)
SPACE = 3          # word space (px)
GAP = 1            # letter gap

def gw(ch): return max(len(r) for r in GL[ch][1])

def width(text):
    w = 0
    for ch in text:
        if ch == " ": w += SPACE
        elif ch in GL: w += gw(ch) + GAP
        else: w += 6 + GAP
    return max(0, w - GAP)

def missing(text): return sorted({c for c in text if c != " " and c not in GL})

def draw(text, put, x, y):
    """put(x, y) for every ink pixel; y = top of the line (caps start here)."""
    for ch in text:
        if ch == " ": x += SPACE; continue
        if ch not in GL:
            top, rows = 0, ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"]
        else: top, rows = GL[ch]
        for r, s in enumerate(rows):
            for c, v in enumerate(s):
                if v == "#": put(x + c, y + top + r)
        x += (max(len(r) for r in rows)) + GAP
    return x
